CREATE TABLE IF NOT EXISTS public.certification_history (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id UUID,
  old_level VARCHAR(20),
  new_level VARCHAR(20),
  reason TEXT,
  validated_by UUID,
  created_at TIMESTAMP DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.properties (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_id UUID,
  name TEXT NOT NULL,
  city TEXT,
  status TEXT DEFAULT 'draft'
);

CREATE TABLE IF NOT EXISTS public.housing (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id INTEGER UNIQUE,
  nom_logement TEXT,
  ville TEXT,
  adresse TEXT,
  plateforme TEXT,
  statut TEXT,
  photo_principale TEXT,
  infos JSONB,
  proprietaire JSONB,
  location JSONB,
  menage JSONB,
  planning JSONB,
  documents JSONB,
  notes JSONB,
  tarifs JSONB,
  contrat JSONB,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.service_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  label TEXT NOT NULL,
  icon TEXT
);

CREATE TABLE IF NOT EXISTS public.services_catalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL,
  service TEXT NOT NULL,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  service_type_id INTEGER
);

CREATE TABLE IF NOT EXISTS public.services_pricing (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id UUID NOT NULL,
  service_id BIGINT,
  label TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'fixed',
  amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
  unit TEXT DEFAULT 'EUR',
  is_default BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  property_type TEXT,
  surface_min NUMERIC,
  surface_max NUMERIC,
  estimated_duration NUMERIC
);

CREATE TABLE IF NOT EXISTS public.services_contracts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id UUID,
  title TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE,
  status TEXT DEFAULT 'actif',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);
