-- Minimal legacy schema required by the first tracked migrations.
-- The pre-2026-02-23 schema existed on the linked project before migration
-- history was introduced, so this bootstrap is deliberately idempotent.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key VARCHAR(50) NOT NULL UNIQUE,
  label VARCHAR(100) NOT NULL,
  icon VARCHAR(100),
  image TEXT,
  description TEXT,
  group_key VARCHAR(50),
  new_id UUID NOT NULL DEFAULT gen_random_uuid()
);

CREATE TABLE IF NOT EXISTS public.user_roles (
  code TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  ordre INTEGER DEFAULT 0,
  is_pro BOOLEAN DEFAULT false,
  group_key TEXT,
  user_id UUID
);

CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY,
  username TEXT,
  first_name TEXT,
  last_name TEXT,
  email TEXT,
  phone TEXT,
  avatar_url TEXT,
  additional_info TEXT,
  category TEXT DEFAULT 'user',
  option TEXT,
  search_target TEXT,
  role TEXT,
  password TEXT,
  created_at TIMESTAMPTZ DEFAULT timezone('utc', now()),
  updated_at DATE,
  location TEXT,
  avatar_scale NUMERIC(3, 2),
  avatar_offset_x NUMERIC,
  avatar_offset_y NUMERIC,
  avatar_rotation NUMERIC,
  avatar_width INTEGER,
  avatar_height INTEGER,
  company_name TEXT,
  legal_form TEXT,
  siret TEXT,
  siren TEXT,
  vat_number TEXT,
  street_address TEXT,
  city TEXT,
  postal_code TEXT,
  country TEXT DEFAULT 'France',
  website TEXT,
  linkedin TEXT,
  instagram TEXT,
  facebook TEXT,
  insurance_number TEXT,
  insurance_company TEXT,
  service_area TEXT,
  service_radius_km INTEGER,
  hourly_rate INTEGER,
  monthly_rate INTEGER,
  availability_hours TEXT,
  emergency_service BOOLEAN DEFAULT false,
  certifications TEXT,
  years_experience INTEGER,
  iban TEXT,
  bic TEXT,
  travel_fee NUMERIC,
  experience_level TEXT,
  certification_level VARCHAR(20) DEFAULT 'none',
  certification_date TIMESTAMP,
  certification_expires_at TIMESTAMP,
  certification_metadata JSONB DEFAULT '{}'::jsonb,
  status TEXT DEFAULT 'active',
  onboarding_complete BOOLEAN NOT NULL DEFAULT false,
  onboarding_completed_at TIMESTAMPTZ,
  intervention_zone_locked BOOLEAN NOT NULL DEFAULT false,
  image TEXT,
  CONSTRAINT profiles_experience_level_check CHECK (
    experience_level IS NULL OR experience_level IN ('debutant', 'intermediaire', 'experimente')
  )
);

-- Minimal reference data needed by the local multi-role workspace fixtures.
